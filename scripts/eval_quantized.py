"""FP32 vs INT8 (IMX500) accuracy for one training run. Run inside WSL2 (IMX models are
Linux-only):

    python scripts/eval_quantized.py --run y11n_320_baseline

Evaluates runs/detector/<run>/weights/best.pt and every best_cal<N>_imx_model/ next to it
on the val and public test splits with identical settings (CPU, same imgsz), and writes
results/detector/<run>/quantization.{md,json}.

The IMX numbers come from Ultralytics' IMX backend: the MCT-quantized ONNX model run on the
CPU, i.e. an emulation of the on-chip INT8 network, not a measurement on the IMX500 itself.
Calibration images are drawn from the VAL split, so the TEST split is the unbiased comparison.
"""

from __future__ import annotations

import argparse
import json
import platform
import re
import time
from pathlib import Path

from dronevision.config import REPO_ROOT, load_config, platform_dataset_yaml

SPLITS = ("val", "test")


def evaluate(weights: Path, data: Path, split: str, imgsz: int, project: Path) -> dict:
    from ultralytics import YOLO

    model = YOLO(str(weights), task="detect")
    t0 = time.time()
    m = model.val(
        data=str(data),
        split=split,
        imgsz=imgsz,
        batch=1,
        device="cpu",
        plots=False,
        verbose=False,
        project=str(project),
        name=f"{weights.name}_{split}",
        exist_ok=True,
    )
    names = m.names
    per_class = {
        names[int(c)]: round(float(m.box.ap50[i]), 4) for i, c in enumerate(m.box.ap_class_index)
    }
    return {
        "mAP50": round(float(m.box.map50), 4),
        "mAP50_95": round(float(m.box.map), 4),
        "precision": round(float(m.box.mp), 4),
        "recall": round(float(m.box.mr), 4),
        "per_class_mAP50": per_class,
        "eval_time_s": round(time.time() - t0, 1),
    }


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--run", required=True)
    p.add_argument("--config", default="detector")
    p.add_argument("--splits", nargs="+", default=list(SPLITS), choices=SPLITS)
    p.add_argument("--cal", nargs="+", type=int, help="only these calibration sizes (e.g. 314)")
    args = p.parse_args(argv)
    if platform.system() != "Linux":
        raise SystemExit("IMX models only run on Linux: run this inside WSL2.")

    cfg = load_config(args.config)
    data = platform_dataset_yaml(cfg["dataset"])
    wdir = REPO_ROOT / cfg["project"] / args.run / "weights"
    res = REPO_ROOT / "results" / "detector" / args.run
    imgsz = cfg["export"]["imx"]["imgsz"]

    models: list[dict] = [
        {"name": "FP32 (best.pt)", "dtype": "FP32", "cal": None, "path": wdir / "best.pt"}
    ]
    for d in sorted(
        wdir.glob("best_cal*_imx_model"), key=lambda x: int(re.findall(r"\d+", x.name)[0])
    ):
        n = int(re.search(r"_cal(\d+)_", d.name).group(1))
        if args.cal and n not in args.cal:
            continue
        export = res / f"imx_export_cal{n}.json"
        mem = (
            json.loads(export.read_text())["memory_report"]["Memory Report"]
            if export.is_file()
            else {}
        )
        models.append(
            {
                "name": f"INT8 IMX, {n} cal. images",
                "dtype": "INT8",
                "cal": n,
                "path": d,
                "memory": mem,
            }
        )

    rows = []
    for mdl in models:
        for split in args.splits:
            print(f"evaluating {mdl['name']} on {split} ...", flush=True)
            r = evaluate(mdl["path"], data, split, imgsz, wdir.parent / "eval")
            rows.append(
                {
                    "model": mdl["name"],
                    "dtype": mdl["dtype"],
                    "calibration_images": mdl["cal"],
                    "split": split,
                    **r,
                    "imx_memory": mdl.get("memory", {}),
                }
            )

    fp32 = {r["split"]: r for r in rows if r["dtype"] == "FP32"}
    lines = [
        f"# FP32 vs INT8 (IMX500): `{args.run}`",
        "",
        "Generated by `scripts/eval_quantized.py` (WSL2, CPU). INT8 = Ultralytics IMX backend "
        "(MCT-quantized ONNX emulated on CPU), not measured on the chip. Calibration images come "
        "from **val**, so **test** is the unbiased comparison. imgsz "
        f"{imgsz}; test = HaGRID test + COCO val2017 balls (not own clips).",
        "",
        "| model | split | mAP50 | Δ vs FP32 | mAP50-95 | hand mAP50 | ball mAP50 | P | R |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in sorted(rows, key=lambda r: (r["split"] != "test", r["calibration_images"] or 0)):
        base = fp32[r["split"]]["mAP50"]
        delta = "—" if r["dtype"] == "FP32" else f"{r['mAP50'] - base:+.4f}"
        pc = r["per_class_mAP50"]
        lines.append(
            f"| {r['model']} | {r['split']} | {r['mAP50']:.4f} | {delta} | {r['mAP50_95']:.4f} | "
            f"{pc.get('hand', float('nan')):.4f} | {pc.get('ball', float('nan')):.4f} | "
            f"{r['precision']:.3f} | {r['recall']:.3f} |"
        )
    lines += [
        "",
        "IMX500 on-chip memory (from each export's memory report):",
        "",
        "| export | memory usage | of available | fits |",
        "|---|---:|---:|---|",
    ]
    for mdl in models[1:]:
        m = mdl.get("memory", {})
        usage, util = m.get("Memory Usage", "?"), m.get("Memory Utilization", "?")
        total, fits = m.get("Total Memory Available On Chip", "?"), m.get("Fit In Chip", "?")
        lines.append(f"| {mdl['name']} | {usage} | {util} of {total} | {fits} |")
    lines.append("")
    res.mkdir(parents=True, exist_ok=True)
    (res / "quantization.md").write_text("\n".join(lines), encoding="utf-8")
    (res / "quantization.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
